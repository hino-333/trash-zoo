/* 端末のタイムゾーンから地域を決める。ユーザーには選ばせない。 */
function regionFromDevice(){
  const off = -new Date().getTimezoneOffset()/60;
  const zone = (Intl.DateTimeFormat().resolvedOptions().timeZone||'').toLowerCase();
  if(zone.startsWith('australia')||zone.startsWith('pacific/auck')) return 'oceania';
  if(zone.startsWith('africa')) return 'africa';
  if(off >= 9.5)  return 'oceania';
  if(off >= 7.5)  return 'eastasia';
  if(off >= 6.5)  return 'seasia';
  if(off >= 4.75) return 'sasia';
  if(off >= 2.5)  return zone.startsWith('europe') ? 'easteu' : 'mideast';
  if(off >= 1.5)  return 'africa';
  if(off >= 0.5)  return zone.includes('stockholm')||zone.includes('oslo')||zone.includes('helsinki')||zone.includes('copenhagen') ? 'northeu' : 'westeu';
  if(off >= -1)   return 'westeu';
  if(off >= -4.5) return 'latam';
  return 'namerica';
}

